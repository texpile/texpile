// Generates a UNIFORM edit set for any fixture, so the instant/tinted/recompile split is
// comparable across documents instead of reflecting hand-picked scenarios per paper.
//
// One scenario per sampled body prose line: insert a word mid-paragraph, which is the
// commonest real edit and the one the instant path is meant to serve. Lines that are markup,
// comments, or too short to anchor on are skipped -- their behaviour is a separate question.
//
// Usage: node tests/live/gen-paper-scenarios.mjs <fixture> [count] > paper-scenarios.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const fixture = process.argv[2];
const want = Number(process.argv[3] || 24);
const src = fs.readFileSync(path.join(here, 'fixtures', fixture, 'main.tex'), 'utf8').split(/\r?\n/);

const start = src.findIndex((l) => l.includes('\\begin{document}'));
const cands = [];
for (let i = Math.max(0, start); i < src.length; i++) {
	const l = src[i];
	const t = l.trim();
	if (!t || t.startsWith('%') || t.startsWith('\\')) continue;
	if (/\\(begin|end|label|ref|cite|includegraphics|input|item)\b/.test(t)) continue;
	// an anchor must be unique in the file, or the driver cannot place the edit
	const words = t.match(/\b[A-Za-z][a-z]{4,}\b/g) || [];
	const anchor = words.find((w) => src.join('\n').split(w).length === 2);
	if (!anchor) continue;
	cands.push({ line: i + 1, anchor });
}

// spread the sample through the document rather than taking the first N: page position
// changes what an edit has to do (a mid-column edit pushes, a page-top edit may not)
const step = Math.max(1, Math.floor(cands.length / want));
const picked = [];
for (let i = 0; i < cands.length && picked.length < want; i += step) picked.push(cands[i]);

const scenarios = picked.map((c) => ({
	name: `L${String(c.line).padStart(4, '0')}-insert`,
	anchor: c.anchor,
	op: { t: 'append', text: ' genuinely' },
	expect: ['EXACT', 'PROV', 'RECOMPILE'],
	maxMs: 90000
}));

process.stdout.write(
	`// GENERATED by gen-paper-scenarios.mjs -- uniform mid-paragraph insert per sampled line.\n` +
		`export { applyOp } from './scenarios.mjs';\n\n` +
		`export const FIXTURES = ${JSON.stringify([{ name: fixture, scenarios }], null, '\t')};\n`
);
console.error(`${fixture}: ${cands.length} candidate lines, sampled ${scenarios.length}`);
