// Regenerates src/typst/symbol-data.ts: every `sym` name Typst math knows, in codex's declaration
// order (which decides what a bare `arrow` or `dots` resolves to), and the math shorthands.
//
// Run it when Typst moves to a new codex. Both sources are read from the tags Typst ships with.
//
//   node scripts/gen-typst-symbols.mjs [sym.txt path or URL] [typst-syntax ast.rs path or URL]
import fs from 'node:fs';
import path from 'node:path';
import * as prettier from 'prettier';

const CODEX = 'v0.3.0';
const TYPST = 'v0.15.1';
const symSource =
  process.argv[2] ??
  `https://raw.githubusercontent.com/typst/codex/${CODEX}/src/modules/sym.txt`;
const astSource =
  process.argv[3] ??
  `https://raw.githubusercontent.com/typst/typst/${TYPST}/crates/typst-syntax/src/ast.rs`;
const OUT = path.join(import.meta.dirname, '../src/typst/symbol-data.ts');

async function read(source) {
  if (!/^https?:/.test(source)) return fs.readFileSync(source, 'utf8');
  const response = await fetch(source);
  if (!response.ok) throw new Error(`${source}: ${response.status}`);
  return response.text();
}

/** codex's decode_value: `\u{XXXX}` and `\vs{N}` escapes, everything else verbatim */
function decode(text) {
  return text
    .replace(/\\u\{([0-9a-fA-F]+)\}/g, (_, hex) =>
      String.fromCodePoint(parseInt(hex, 16))
    )
    .replace(/\\vs\{(\w+)\}/g, (_, vs) =>
      String.fromCodePoint(
        vs === 'text' ? 0xfe0e : vs === 'emoji' ? 0xfe0f : 0xfdff + Number(vs)
      )
    );
}

/** name -> its value, or its variants as [modifiers, value] in declaration order; and the deprecated names */
function parseSym(text) {
  const out = {};
  const deprecated = [];
  const modules = [];
  let current = null;
  let base = '';
  let pendingDeprecation = false;
  for (const raw of text.split('\n')) {
    const line = raw.split('//')[0].trim();
    if (!line) continue;
    if (line.startsWith('@deprecated:')) {
      pendingDeprecation = true;
      continue;
    }
    const space = line.indexOf(' ');
    const head = space < 0 ? line : line.slice(0, space);
    const tail = space < 0 ? undefined : line.slice(space + 1).trim();
    let name;
    if (tail === '{') {
      modules.push(head);
      current = null;
      name = modules.join('.');
    } else if (head === '}') {
      modules.pop();
      current = null;
    } else if (head.startsWith('.')) {
      current.push([head.slice(1), decode(tail)]);
      name = `${base}${head}`;
    } else {
      base = [...modules, head].join('.');
      current = tail === undefined ? [] : [['', decode(tail)]];
      out[base] = current;
      name = base;
    }
    if (pendingDeprecation && name) deprecated.push(name);
    pendingDeprecation = false;
  }
  for (const [name, variants] of Object.entries(out)) {
    if (variants.length === 1 && variants[0][0] === '')
      out[name] = variants[0][1];
  }
  return { symbols: out, deprecated };
}

/** typst-syntax's MathShorthand::LIST */
function parseShorthands(text) {
  const list = text.match(
    /struct MathShorthand[\s\S]*?LIST[^=]*=\s*&\[([\s\S]*?)\];/
  );
  if (!list) throw new Error('MathShorthand::LIST not found');
  return Object.fromEntries(
    [...list[1].matchAll(/\("((?:[^"\\]|\\.)+)",\s*'(.)'\)/g)].map((m) => [
      m[1],
      m[2],
    ])
  );
}

/** JSON, with invisible and combining characters written as escapes so the file can be read */
function literal(value) {
  return JSON.stringify(value).replace(/[^\P{C}]|[^\P{Z} ]|\p{M}/gu, (ch) => {
    const cp = ch.codePointAt(0);
    return cp > 0xffff
      ? `\\u{${cp.toString(16)}}`
      : `\\u${cp.toString(16).padStart(4, '0')}`;
  });
}

const { symbols, deprecated } = parseSym(await read(symSource));
const shorthands = parseShorthands(await read(astSource));

const source = `// GENERATED by scripts/gen-typst-symbols.mjs from typst/codex ${CODEX} (src/modules/sym.txt)
// and typst ${TYPST} (typst-syntax's MathShorthand::LIST). Do not edit by hand.

/** a symbol's value, or its variants as [modifiers, value] in declaration order */
export type TypstSymbolEntry = string | readonly (readonly [string, string])[];

export const TYPST_SYMBOLS: Readonly<Record<string, TypstSymbolEntry>> = ${literal(symbols)};

export const TYPST_MATH_SHORTHANDS: Readonly<Record<string, string>> = ${literal(shorthands)};

/** names Typst still reads but warns about (whole symbols, modules and single variants) */
export const TYPST_DEPRECATED: ReadonlySet<string> = new Set(${literal(deprecated)});
`;

const config = await prettier.resolveConfig(OUT);
fs.writeFileSync(
  OUT,
  await prettier.format(source, { ...config, filepath: OUT })
);
console.log(
  `${Object.keys(symbols).length} symbols, ${deprecated.length} deprecated, ${Object.keys(shorthands).length} shorthands -> ${path.relative(process.cwd(), OUT)}`
);
